"""설정 파일의 seq: auto를 TestSplit.txt 기준으로 확정해 resolved config 생성.

사용(experiments/ 기준):
    python -B scripts/resolve_autoseq.py --config configs/ext_v2.yaml \
        --out configs/_ext_v2_resolved.yaml

배경: 7-Scenes TestSplit.txt는 'sequence2' 형태로 쓰지만 디스크 디렉터리는
'seq-02'다. 서버 스크립트 11의 인라인 resolver가 이 매핑을 빠뜨려 auto
장면 5개(heads/office/pumpkin/redkitchen/stairs)가 데이터가 정상임에도 전부
drop됐다. 매핑 로직은 본 스크립트로 이관해 단위 테스트로 보호한다.

exit code: 0 = 전부 확정, 3 = drop 발생(해당 시퀀스 제외하고 파일은 생성).
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from weather3d.config import load_config  # noqa: E402


def seq_dir_name(candidate: str) -> str:
    """'sequence2' -> 'seq-02'. 이미 seq-01 형태면 그대로 반환."""
    m = re.fullmatch(r"sequence(\d+)", candidate.strip())
    if m:
        return f"seq-{int(m.group(1)):02d}"
    return candidate.strip()


def _first_frame_dir(scene_dir: Path, names: list[str]) -> str | None:
    for n in names:
        if any((scene_dir / n).glob("frame-*.color.png")):
            return n
    return None


def resolve_config(cfg: dict) -> tuple[list[dict], list[str], list[str]]:
    """seq: auto 확정 + 존재 검사. (kept, dropped, resolve_log) 반환."""
    cfgp = Path(cfg["_config_path"])
    data = cfg["data"]

    def root_of(key: str) -> Path:
        p = Path(data[key])
        return p if p.is_absolute() else (cfgp.parent / p).resolve()

    s7 = root_of("seven_scenes_root")
    nrgbd = root_of("neural_rgbd_root")
    ta = root_of("tartanair2_root") if "tartanair2_root" in data else None

    kept: list[dict] = []
    dropped: list[str] = []
    log: list[str] = []
    for s in data["sequences"]:
        s = dict(s)
        if s["dataset"] == "seven_scenes":
            sd = s7 / s["scene"]
            if s["seq"] == "auto":
                cands: list[str] = []
                for split in ("TestSplit.txt", "TrainSplit.txt"):
                    p = sd / split
                    if p.is_file():
                        cands = [seq_dir_name(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]
                        break
                cands = cands or sorted(d.name for d in sd.glob("seq-*") if d.is_dir())
                pick = _first_frame_dir(sd, cands)
                if pick is None:
                    dropped.append(s["id"])
                    log.append(f"[DROP] {s['id']}: 후보 {cands} 중 사용 가능한 seq 없음")
                    continue
                s["seq"] = pick
                log.append(f"[RESOLVE] {s['id']} -> {pick}")
            if not any((sd / s["seq"]).glob("frame-*.color.png")):
                dropped.append(s["id"])
                log.append(f"[DROP] {s['id']}: {s['seq']} 프레임 없음")
                continue
        elif s["dataset"] == "neural_rgbd":
            if not (nrgbd / s["scene"] / "images").is_dir():
                dropped.append(s["id"])
                log.append(f"[DROP] {s['id']}: images/ 없음")
                continue
        elif s["dataset"] == "tartanair2":
            if ta is None:
                dropped.append(s["id"])
                log.append(f"[DROP] {s['id']}: tartanair2_root 미설정")
                continue
            rel = f"{s['env']}/Data_{s['difficulty']}/extracted/{s['env']}/Data_{s['difficulty']}/{s['traj']}"
            if not (ta / rel / "image_lcam_front").is_dir():
                dropped.append(s["id"])
                log.append(f"[DROP] {s['id']}: {rel} 없음")
                continue
        kept.append(s)
    return kept, dropped, log


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=str(ROOT / "configs" / "ext_v2.yaml"))
    ap.add_argument("--out", default=None, help="미지정 시 <config와 같은 폴더>/_<이름>_resolved.yaml")
    args = ap.parse_args()

    cfg = load_config(args.config)
    kept, dropped, log = resolve_config(cfg)
    for line in log:
        print(line)

    cfg["data"]["sequences"] = kept
    src = Path(cfg["_config_path"])
    out = Path(args.out) if args.out else src.parent / f"_{src.stem}_resolved.yaml"
    header = (
        f"# AUTO-GENERATED by scripts/resolve_autoseq.py from {src.name} at "
        + time.strftime("%Y-%m-%dT%H:%M:%S%z")
        + " - 직접 수정 금지\n"
    )
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"[OK] resolved {len(kept)} sequences (dropped: {dropped or '없음'}) -> {out}")
    return 0 if not dropped else 3


if __name__ == "__main__":
    raise SystemExit(main())
